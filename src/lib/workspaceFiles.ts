/**
 * Workspace (project-level) skills & instructions delivery
 * (trellis-workspace-scope design D4/D5). Unlike global delivery (symlinks
 * into `~/.trellis/`), workspace skills are COPIED into the agent's
 * project-level directory — rendered artifacts must be committable to the
 * repo and usable on filesystems without symlink support.
 *
 * A copy has no symlink-realpath ownership proof, so ownership mirrors the
 * MCP ledger instead: one `.trellis-workspace.json` per destination root
 * maps skill name → { source, sourceDigest, destDigest }. A delivered
 * directory is "ours" only while its current digest still equals the
 * recorded `destDigest`; a hand-edited copy is a conflict, never touched —
 * the same posture mcpOwnership gives bare JSON/TOML keys.
 *
 * Instructions are delivered as marker-headed file copies: root `AGENTS.md`
 * (read natively by Codex, pi, and Kimi Code) and Kiro's
 * `.kiro/steering/trellis-workspace.md`. Claude Code reads `CLAUDE.md`, not
 * `AGENTS.md`, and a repo's `CLAUDE.md` is almost always user-authored —
 * v1 deliberately writes no Claude instructions file (documented
 * limitation; `migrate --workspace` is the path for absorbing one).
 */

import { existsSync, mkdirSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import type { AdapterPlanItem } from "../core/adapter.js";
import { isInScope } from "../core/adapter.js";
import type { AgentId, CanonicalSource } from "../core/types.js";
import { directoryDigest } from "./dirDigest.js";
import type { BackupSession } from "./backup.js";

/** Per-destination-root ledger of Trellis-owned workspace copies. */
export type WorkspaceCopyLedger = Record<string, { source: string; sourceDigest: string; destDigest: string }>;

const COPY_LEDGER_NAME = ".trellis-workspace.json";
/** Exported for `migrate --workspace` (trellis-workspace-scope task 4.x):
 * absorbing a root `AGENTS.md` rewrites it marker-headed in place, which
 * must be byte-identical to what a later sync would render. */
export const INSTRUCTIONS_MARKER = "<!-- generated by trellis from .agents/AGENTS.md — do not edit; run `trellis sync` to refresh -->";

/** Agents that read `.agents/skills/` natively get no copy at all — the
 * canonical directory is itself the deliverable. zcode's Runtime-only
 * delivery owns its skills through the Runtime provider (task 2.2). */
const COPY_TARGETS: Partial<Record<AgentId, string>> = {
  "claude-code": join(".claude", "skills"),
  kiro: join(".kiro", "skills"),
};

interface InstructionsTarget {
  /** Relative to the workspace root. */
  relPath: string;
  /** Agents sharing this target file (documentation value only). */
  forAgents: string;
}

function instructionsTargets(agentId: AgentId): InstructionsTarget[] {
  switch (agentId) {
    case "codex":
    case "pi":
    case "kimi-code":
      return [{ relPath: "AGENTS.md", forAgents: "Codex/pi/Kimi Code" }];
    case "kiro":
      return [{ relPath: join(".kiro", "steering", "trellis-workspace.md"), forAgents: "Kiro" }];
    default:
      return [];
  }
}

function loadCopyLedger(path: string): WorkspaceCopyLedger {
  if (!existsSync(path)) return {};
  try {
    return JSON.parse(readFileSync(path, "utf-8")) as WorkspaceCopyLedger;
  } catch {
    return {}; // corrupt ledger — treat as "nothing recorded", never crash a sync
  }
}

function planWorkspaceSkillCopies(agentId: AgentId, canonical: CanonicalSource): AdapterPlanItem[] {
  const workspace = canonical.workspace;
  const relRoot = COPY_TARGETS[agentId];
  if (!workspace || !relRoot) return [];
  const destRoot = join(workspace.root, relRoot);
  const ledgerPath = join(destRoot, COPY_LEDGER_NAME);
  const ledger = loadCopyLedger(ledgerPath);
  const items: AdapterPlanItem[] = [];

  const desired = canonical.skills.filter(
    (skill) => workspace.skillProvenance[skill.name] === "workspace" && isInScope(agentId, skill.scope, canonical.managedAgents),
  );
  const desiredNames = new Set(desired.map((s) => s.name));

  for (const skill of desired) {
    const dest = join(destRoot, skill.name);
    if (!existsSync(dest)) {
      items.push({
        action: "create",
        kind: "skill",
        layer: "workspace",
        target: dest,
        copyFrom: skill.dir,
        description: `workspace skill "${skill.name}" copied to ${dest}`,
      });
      continue;
    }
    const recorded = ledger[skill.name];
    if (!recorded) {
      items.push({
        action: "conflict",
        kind: "skill",
        layer: "workspace",
        target: dest,
        description: `${dest} exists and is not a Trellis-managed workspace copy — left untouched`,
        remediation: `run \`trellis migrate --workspace\` to absorb it into .agents/, or remove it and re-run sync`,
      });
      continue;
    }
    if (directoryDigest(dest) !== recorded.destDigest) {
      items.push({
        action: "conflict",
        kind: "skill",
        layer: "workspace",
        target: dest,
        description: `${dest} was hand-edited since Trellis wrote it — left untouched`,
        remediation: `merge your edits into .agents/skills/${skill.name}/ (the canonical copy), then remove ${dest} and re-run sync — Trellis will not overwrite hand edits`,
      });
      continue;
    }
    if (directoryDigest(skill.dir) === recorded.sourceDigest) {
      continue; // fresh — no-op
    }
    items.push({
      action: "create",
      kind: "skill",
      layer: "workspace",
      target: dest,
      copyFrom: skill.dir,
      description: `workspace skill "${skill.name}" re-copied to ${dest} (source changed)`,
    });
  }

  for (const name of Object.keys(ledger)) {
    if (desiredNames.has(name)) continue;
    const dest = join(destRoot, name);
    if (!existsSync(dest)) {
      // Stale ledger entry only — rewrite the ledger (no dir to remove).
      items.push({
        action: "remove",
        kind: "skill",
        layer: "workspace",
        target: dest,
        description: `stale workspace-copy ledger entry "${name}" pruned from ${ledgerPath}`,
      });
      continue;
    }
    if (directoryDigest(dest) !== ledger[name].destDigest) {
      continue; // hand-edited since we wrote it — no longer ours to remove
    }
    items.push({
      action: "remove",
      kind: "skill",
      layer: "workspace",
      target: dest,
      description: `workspace skill "${name}" removed from ${dest} — no longer in .agents/skills/`,
    });
  }

  return items;
}

function planWorkspaceInstructions(agentId: AgentId, canonical: CanonicalSource): AdapterPlanItem[] {
  const workspace = canonical.workspace;
  if (!workspace) return [];
  const items: AdapterPlanItem[] = [];

  for (const target of instructionsTargets(agentId)) {
    const path = join(workspace.root, target.relPath);
    const rendered = workspace.instructionsFile
      ? `${INSTRUCTIONS_MARKER}\n\n${readFileSync(workspace.instructionsFile, "utf-8")}`
      : undefined;

    if (rendered === undefined) {
      // Workspace no longer declares instructions — remove the delivered
      // file only while it's still byte-exactly a marker-headed one.
      if (!existsSync(path)) continue;
      const current = readFileSync(path, "utf-8");
      if (!current.startsWith(INSTRUCTIONS_MARKER)) continue; // user's file — never ours
      items.push({
        action: "remove",
        kind: "instructions",
        layer: "workspace",
        target: path,
        description: `${path} removed — .agents/AGENTS.md no longer exists`,
      });
      continue;
    }

    if (!existsSync(path)) {
      items.push({
        action: "create",
        kind: "instructions",
        layer: "workspace",
        target: path,
        fileContent: rendered,
        description: `workspace instructions written to ${path} (${target.forAgents})`,
      });
      continue;
    }
    const current = readFileSync(path, "utf-8");
    if (current === rendered) continue;
    if (!current.startsWith(INSTRUCTIONS_MARKER)) {
      items.push({
        action: "conflict",
        kind: "instructions",
        layer: "workspace",
        target: path,
        description: `${path} exists and is not Trellis-generated — left untouched`,
        remediation: `merge its content into .agents/AGENTS.md (e.g. via \`trellis migrate --workspace\`) and remove the file, then re-run sync`,
      });
      continue;
    }
    items.push({
      action: "create",
      kind: "instructions",
      layer: "workspace",
      target: path,
      fileContent: rendered,
      description: `workspace instructions updated in ${path} (source changed)`,
    });
  }

  return items;
}

export function planWorkspaceFiles(agentId: AgentId, canonical: CanonicalSource): AdapterPlanItem[] {
  return [...planWorkspaceSkillCopies(agentId, canonical), ...planWorkspaceInstructions(agentId, canonical)];
}

/** Executes a `planWorkspaceFiles` result through the run's backup session
 * and rewrites the copy ledger for every destination root it touched. */
export function applyWorkspaceFiles(agentId: AgentId, canonical: CanonicalSource, items: AdapterPlanItem[], backup: BackupSession): void {
  const workspace = canonical.workspace;
  if (!workspace) return;

  for (const item of items) {
    if (item.layer !== "workspace" || item.action === "conflict") continue;

    if (item.kind === "instructions") {
      if (item.action === "create" && item.fileContent !== undefined) {
        // Kiro's steering dir (and any future nested target) may not exist
        // yet in a fresh project — create it before the atomic write.
        mkdirSync(dirname(item.target), { recursive: true });
        backup.writeFile(item.target, item.fileContent);
      } else if (item.action === "remove") {
        // removeDir's snapshot+remove works for single files too (cpSync /
        // rmSync both accept file paths) — rollback restores the file.
        backup.removeDir(item.target);
      }
      continue;
    }

    if (item.kind === "skill") {
      const destRoot = dirname(item.target);
      const ledgerPath = join(destRoot, COPY_LEDGER_NAME);
      let ledger = loadCopyLedger(ledgerPath);
      const name = item.target.slice(destRoot.length + 1);
      if (item.action === "create" && item.copyFrom) {
        if (existsSync(item.target)) {
          backup.replaceDirFromSource(item.target, item.copyFrom);
        } else {
          backup.createDirFromSource(item.target, item.copyFrom);
        }
        ledger = {
          ...ledger,
          [name]: { source: item.copyFrom, sourceDigest: directoryDigest(item.copyFrom), destDigest: directoryDigest(item.target) },
        };
      } else if (item.action === "remove") {
        if (existsSync(item.target)) {
          backup.removeDir(item.target);
        }
        const next = { ...ledger };
        delete next[name];
        ledger = next;
      }
      backup.writeFile(ledgerPath, `${JSON.stringify(ledger, null, 2)}\n`);
    }
  }
}
