#!/usr/bin/env node
/**
 * Bundles src/pi-bridge/index.ts into a single, dependency-free
 * dist/pi-bridge/bundle.js (trellis-pi-mcp-bridge-p4 design.md D6).
 *
 * Why bundling is required, not optional: the bridge is delivered as a
 * symlink into an arbitrary user's `~/.pi/agent/extensions/`. Node's
 * loader resolves that file's own bare-specifier imports (`typebox`,
 * `@modelcontextprotocol/sdk`) relative to the *symlink's own path*, not
 * its realpath — confirmed empirically in the real sandbox (a plain,
 * unbundled `src/pi-bridge/index.ts` symlink failed with "Cannot find
 * module '@modelcontextprotocol/sdk/client/index.js'", require stack
 * rooted at the symlink path, not Trellis's install directory). A user's
 * home directory has no node_modules ancestor, so this can never resolve
 * regardless of what Trellis's own package.json declares. Bundling every
 * third-party import (node builtins excluded — always resolvable
 * regardless of location) removes the need for any resolution at all.
 */
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

await build({
  entryPoints: [join(repoRoot, "src", "pi-bridge", "index.ts")],
  outfile: join(repoRoot, "dist", "pi-bridge", "bundle.js"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  packages: "bundle",
  banner: { js: "// Generated by scripts/build-pi-bridge.mjs — do not edit directly." },
});

console.log("Built dist/pi-bridge/bundle.js");
